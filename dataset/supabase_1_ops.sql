-- Governed data products (views) for the semantic layer. Agents should query these, not raw tables.
-- Every "today" calculation uses ops.meta.as_of_date.
SET search_path = ops;

CREATE OR REPLACE VIEW as_of AS SELECT value::date AS as_of_date FROM meta WHERE key = 'as_of_date';

-- One row per project: money, delivery, schedule and the burn gap.
CREATE OR REPLACE VIEW v_project_health AS
WITH spend AS (SELECT project_id, sum(amount_usd) AS spent_usd FROM expenditures GROUP BY project_id),
     delivery AS (SELECT project_id,
        round(sum(weight*percent_complete)/sum(weight), 1) AS delivery_pct,
        count(*) FILTER (WHERE status <> 'Completed' AND planned_end < (SELECT as_of_date FROM as_of)) AS late_activities
      FROM activities GROUP BY project_id)
SELECT p.project_id, p.name, p.county, d.name AS donor, p.theme, p.status,
  p.budget_total_usd, s.spent_usd,
  round(100.0*s.spent_usd/p.budget_total_usd, 1) AS utilization_pct,
  round(100.0*p.planned_utilization_to_date, 1) AS planned_utilization_pct,
  round(100.0*s.spent_usd/p.budget_total_usd - 100.0*p.planned_utilization_to_date, 1) AS burn_vs_plan_pts,
  dl.delivery_pct, dl.late_activities,
  round(100.0*s.spent_usd/p.budget_total_usd - dl.delivery_pct, 1) AS burn_delivery_gap_pts,
  p.budget_total_usd - s.spent_usd AS remaining_usd,
  p.end_date, p.end_date - (SELECT as_of_date FROM as_of) AS days_to_end
FROM projects p JOIN donors d USING (donor_id)
JOIN spend s USING (project_id) JOIN delivery dl USING (project_id);

CREATE OR REPLACE VIEW v_budget_by_line AS
SELECT b.project_id, p.name AS project, b.category, b.budget_usd,
  coalesce(sum(e.amount_usd),0) AS spent_usd,
  round(100.0*coalesce(sum(e.amount_usd),0)/b.budget_usd, 1) AS line_utilization_pct
FROM budget_lines b JOIN projects p USING (project_id)
LEFT JOIN expenditures e USING (line_id)
GROUP BY b.line_id, b.project_id, p.name, b.category, b.budget_usd;

CREATE OR REPLACE VIEW v_burn_monthly AS
SELECT e.project_id, e.month, b.category, sum(e.amount_usd) AS spent_usd
FROM expenditures e JOIN budget_lines b USING (line_id) GROUP BY 1,2,3;

-- Org-wide travel spend by quarter (policy question: is there a ceiling?)
CREATE OR REPLACE VIEW v_travel_by_quarter AS
SELECT date_trunc('quarter', month)::date AS quarter_start, sum(spent_usd) AS travel_usd
FROM v_burn_monthly WHERE category = 'Travel' GROUP BY 1;

CREATE OR REPLACE VIEW v_open_vacancies AS
SELECT v.vacancy_id, v.project_id, p.name AS project, v.role, v.opened_date,
  (SELECT as_of_date FROM as_of) - v.opened_date AS days_open, v.stage, v.applicants,
  pe.full_name AS interim_cover
FROM hr_vacancies v JOIN projects p USING (project_id)
LEFT JOIN people pe ON pe.person_id = v.interim_cover_person_id;

CREATE OR REPLACE VIEW v_contract_expiry AS
SELECT pe.person_id, pe.full_name, pe.role, pe.contract_end_date,
  pe.contract_end_date - (SELECT as_of_date FROM as_of) AS days_left,
  string_agg(DISTINCT p.name, '; ') AS projects
FROM people pe LEFT JOIN project_staff ps USING (person_id) LEFT JOIN projects p ON p.project_id = ps.project_id
WHERE pe.contract_end_date IS NOT NULL GROUP BY pe.person_id, pe.full_name, pe.role, pe.contract_end_date;

CREATE OR REPLACE VIEW v_pending_procurement AS
SELECT r.request_id, r.project_id, p.name AS project, r.item, r.supplier, r.amount_usd, r.requested_date,
  (SELECT as_of_date FROM as_of) - r.requested_date AS days_pending, r.status
FROM procurement_requests r JOIN projects p USING (project_id) WHERE r.status <> 'Delivered';

CREATE OR REPLACE VIEW v_upcoming_deadlines AS
SELECT d.deadline_id, d.project_id, p.name AS project, dn.name AS donor, d.title, d.due_date,
  d.due_date - (SELECT as_of_date FROM as_of) AS days_left, d.status
FROM deadlines d JOIN projects p USING (project_id) JOIN donors dn ON dn.donor_id = d.donor_id
WHERE d.due_date >= (SELECT as_of_date FROM as_of);

-- Projects with no Maintenance budget line (sustainability risk)
CREATE OR REPLACE VIEW v_projects_without_maintenance AS
SELECT p.project_id, p.name, p.status FROM projects p
WHERE NOT EXISTS (SELECT 1 FROM budget_lines b WHERE b.project_id = p.project_id AND b.category = 'Maintenance');

