-- Context operational database (Silo A). Target: PostgreSQL 14+ (a free Supabase project works).
-- Schema: ops. Zetaris reads it in place; the app writes only to ops.decisions.
CREATE SCHEMA IF NOT EXISTS ops;
SET search_path = ops;

CREATE TABLE donors (
  donor_id text PRIMARY KEY, name text NOT NULL, country text,
  reporting_cycle text, contact_email text);
COMMENT ON TABLE donors IS 'Funding organisations and how often they expect reports.';

CREATE TABLE people (
  person_id text PRIMARY KEY, full_name text NOT NULL, role text, county text,
  employment_type text CHECK (employment_type IN ('staff','consultant')),
  contract_end_date date, email text);
COMMENT ON COLUMN people.contract_end_date IS 'Set for consultants only. Null means open-ended staff contract.';

CREATE TABLE projects (
  project_id text PRIMARY KEY, name text NOT NULL, county text,
  donor_id text REFERENCES donors, theme text,
  status text CHECK (status IN ('Active','Closing','Closed')),
  start_date date, end_date date,
  budget_total_usd numeric(12,0) NOT NULL,
  planned_utilization_to_date numeric(4,2));
COMMENT ON COLUMN projects.planned_utilization_to_date IS 'Share of budget finance planned to have spent by the as-of date (0 to 1).';

CREATE TABLE project_staff (
  project_id text REFERENCES projects, person_id text REFERENCES people,
  role_on_project text, allocation_pct int, PRIMARY KEY (project_id, person_id));

CREATE TABLE budget_lines (
  line_id text PRIMARY KEY, project_id text REFERENCES projects,
  category text NOT NULL, budget_usd numeric(12,0) NOT NULL);
COMMENT ON COLUMN budget_lines.category IS 'Personnel, Works & Equipment, Travel, Training, M&E, Maintenance, Overheads. A project without a Maintenance row has no maintenance budget.';

CREATE TABLE expenditures (
  expenditure_id text PRIMARY KEY, project_id text REFERENCES projects,
  line_id text REFERENCES budget_lines, month date NOT NULL,
  amount_usd numeric(12,0) NOT NULL, vendor text);

CREATE TABLE activities (
  activity_id text PRIMARY KEY, project_id text REFERENCES projects,
  name text NOT NULL, weight numeric(4,2) NOT NULL,
  planned_start date, planned_end date, actual_end date,
  percent_complete numeric(5,1) NOT NULL,
  status text CHECK (status IN ('Completed','In progress','Not started')));
COMMENT ON COLUMN activities.weight IS 'Share of the project workplan. Weights per project sum to 1.';

CREATE TABLE procurement_requests (
  request_id text PRIMARY KEY, project_id text REFERENCES projects, item text,
  supplier text, amount_usd numeric(12,0), requested_date date, status text, owner_person_id text REFERENCES people);

CREATE TABLE hr_vacancies (
  vacancy_id text PRIMARY KEY, project_id text REFERENCES projects, role text,
  opened_date date, stage text, applicants int, interim_cover_person_id text REFERENCES people);

CREATE TABLE deadlines (
  deadline_id text PRIMARY KEY, project_id text REFERENCES projects,
  donor_id text REFERENCES donors, title text, due_date date, status text);

-- The only table the application writes to. Agent proposals land here as 'Pending'.
CREATE TABLE decisions (
  decision_id text PRIMARY KEY, project_id text REFERENCES projects,
  title text NOT NULL,
  status text NOT NULL DEFAULT 'Pending' CHECK (status IN ('Pending','Approved','Rejected','Deferred')),
  created_by text, created_at date, decided_by text REFERENCES people, decided_at date, outcome text,
  rationale text, evidence_refs text);

-- Key/value settings. as_of_date is the agent's "today": always read it instead of now().
CREATE TABLE meta (key text PRIMARY KEY, value text);

CREATE INDEX ON expenditures (project_id, month);
CREATE INDEX ON activities (project_id);


